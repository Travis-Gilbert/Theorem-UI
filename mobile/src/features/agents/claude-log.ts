// SOURCING: Claude Code session logs (~/.claude/projects/<folder>/<session id>.jsonl). Undocumented and versioned by Claude Code; the shapes here were read from a Claude Code 2.1 log. Lines: user (string prompt, text blocks, tool_result blocks; isMeta lines are context, not the person), assistant (one content block per line, grouped by message.id, with message.stop_reason), ai-title, and others this reader skips.
//
// Unknown line types and fields are ignored, so a newer Claude Code degrades
// to fewer details rather than a broken conversation.
import {
  assistantTurn,
  formatInput,
  oversizedNote,
  stepFor,
  stepTitle,
  userTurn,
  type Transcript,
} from './transcript'

type Json = Record<string, unknown>
const object = (value: unknown): Json =>
  value && typeof value === 'object' && !Array.isArray(value) ? (value as Json) : {}
const text = (value: unknown) => (typeof value === 'string' ? value : undefined)

/** Claude Code writes these as the person's message when Escape interrupts a turn. */
const INTERRUPTED = /^\[Request interrupted by user[^\]]*\]$/

/**
 * The person's words from a prompt line, without the context Claude Code adds:
 * system reminders, slash-command wrappers and local command output. Returns
 * undefined for a line that is only context.
 */
export function promptText(raw: string): string | undefined {
  if (/^<local-command-(stdout|stderr)>/.test(raw.trim())) return undefined
  if (raw.startsWith('Caveat: The messages below were generated by the user while running local commands'))
    return undefined
  const command = raw.match(/<command-name>([^<]*)<\/command-name>/)
  if (command) {
    const args = raw.match(/<command-args>([\s\S]*?)<\/command-args>/)?.[1]?.trim()
    return [command[1]!.trim(), args].filter(Boolean).join(' ')
  }
  const cleaned = raw
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '')
    .replace(/<\/?(bash-input|bash-stdout|bash-stderr|user-prompt-submit-hook)>/g, '')
    .trim()
  return cleaned || undefined
}

function resultText(content: unknown): string {
  if (typeof content === 'string') return content
  if (Array.isArray(content))
    return content
      .map((part) => {
        const p = object(part)
        return p.type === 'text' ? (text(p.text) ?? '') : p.type === 'image' ? '[image]' : ''
      })
      .filter(Boolean)
      .join('\n')
  return content === undefined ? '' : formatInput(content)
}

/** stop_reason values after which Claude Code waits for the person. */
const FINISHED = new Set(['end_turn', 'stop_sequence', 'max_tokens', 'refusal'])

/** Applies one log line. Returns false for a line that is not JSON. */
export function applyClaudeLine(transcript: Transcript, line: string): boolean {
  let entry: Json
  try {
    entry = object(JSON.parse(line))
  } catch {
    return false
  }
  if (entry.isSidechain === true) return true
  if (typeof entry.cwd === 'string') transcript.cwd ??= entry.cwd
  if (typeof entry.sessionId === 'string') transcript.sessionId ??= entry.sessionId
  const at = text(entry.timestamp)
  const id = text(entry.uuid) ?? `${transcript.turns.length}`

  switch (entry.type) {
    case 'ai-title':
      transcript.title = text(entry.aiTitle) ?? transcript.title
      return true

    case 'theorem-oversized': {
      const toolId = text(entry.id)
      if (toolId) {
        const step = stepFor(transcript, toolId)
        step.result = oversizedNote(Number(entry.bytes) || 0)
        step.done = true
      } else {
        assistantTurn(transcript, id, at).blocks.push({ type: 'note', text: oversizedNote(Number(entry.bytes) || 0) })
      }
      return true
    }

    case 'user': {
      if (entry.isMeta === true || entry.isCompactSummary === true) return true
      const message = object(entry.message)
      const content = message.content
      if (typeof content === 'string') {
        if (INTERRUPTED.test(content.trim())) {
          const last = transcript.turns.at(-1)
          if (last?.role === 'assistant') last.stopped = true
          transcript.open = false
          return true
        }
        const words = promptText(content)
        if (words) {
          userTurn(transcript, id, words, at)
          transcript.open = true
        }
        return true
      }
      if (!Array.isArray(content)) return true
      const words: string[] = []
      for (const part of content) {
        const block = object(part)
        if (block.type === 'tool_result') {
          const step = stepFor(transcript, text(block.tool_use_id) ?? id)
          step.result = resultText(block.content)
          step.isError = block.is_error === true
          step.done = true
        } else if (block.type === 'text') {
          const value = text(block.text) ?? ''
          if (INTERRUPTED.test(value.trim())) {
            const last = transcript.turns.at(-1)
            if (last?.role === 'assistant') last.stopped = true
            transcript.open = false
          } else {
            const cleaned = promptText(value)
            if (cleaned) words.push(cleaned)
          }
        } else if (block.type === 'image') {
          words.push('[image]')
        }
      }
      if (words.length) {
        userTurn(transcript, id, words.join('\n\n'), at)
        transcript.open = true
      }
      return true
    }

    case 'assistant': {
      const message = object(entry.message)
      const turn = assistantTurn(transcript, text(message.id) ?? id, at)
      const content = Array.isArray(message.content) ? message.content : []
      for (const part of content) {
        const block = object(part)
        if (block.type === 'text') {
          const value = text(block.text)?.trim()
          if (value) turn.blocks.push({ type: 'text', text: value })
        } else if (block.type === 'thinking') {
          // Redacted thinking is an empty string with a signature; show only what is readable.
          const value = text(block.thinking)?.trim()
          if (value) turn.blocks.push({ type: 'reasoning', text: value })
        } else if (block.type === 'tool_use') {
          const name = text(block.name) ?? 'tool'
          turn.blocks.push({
            type: 'step',
            step: {
              id: text(block.id) ?? `${id}-${turn.blocks.length}`,
              name,
              title: stepTitle(name, block.input),
              input: formatInput(block.input),
              done: false,
            },
          })
        }
      }
      const stop = text(message.stop_reason)
      transcript.open = !(stop && FINISHED.has(stop))
      return true
    }

    default:
      return true
  }
}

/** A title from the discovery listing's raw fragment of an ai-title or first prompt line. */
export function claudeTitleFragment(fragment: string): string | undefined {
  const ai = fragment.match(/"aiTitle":"((?:[^"\\]|\\.)*)"/)
  if (ai) return decodeFragment(ai[1]!)
  const prompt = fragment.match(/"content":"((?:[^"\\]|\\.)*)/)
  if (!prompt) return undefined
  const words = promptText(decodeFragment(prompt[1]!))
  return words ? words.split('\n')[0]!.slice(0, 120) : undefined
}

/** Decodes a JSON string body that may have been cut mid-escape. */
export function decodeFragment(body: string): string {
  const safe = body.replace(/\\u[0-9a-fA-F]{0,3}$|\\$/, '')
  try {
    return JSON.parse(`"${safe}"`) as string
  } catch {
    return safe
  }
}
