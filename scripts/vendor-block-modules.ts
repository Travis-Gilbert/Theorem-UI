// Vendors the modules live blocks may import (plan D9) from esm.sh, so the
// block listener serves them offline and nothing in a block reaches a CDN.
//
//   bun scripts/vendor-block-modules.ts
//
// Each entry below is an exact-version esm.sh URL. The script follows every
// import, rewrites esm.sh paths to the listener's /vendor/ paths, and writes:
//
// - src/lib/blocks/vendor/files/**: the modules as served
// - src/lib/blocks/vendor/manifest.ts: the import map, the integrity of each
//   served file, and the esm.sh URL and integrity it came from
// - src/lib/blocks/vendor/modules.ts: the files as `?raw` imports, for the
//   listener and the standalone export
//
// To add a module, add its specifier and exact esm.sh URL to ENTRIES and run
// the script again. docs/blocks/live-blocks.md has the details.
import { createHash } from 'node:crypto'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { parse } from 'acorn'
import type { Node as AcornNode } from 'acorn'
import { simple } from 'acorn-walk'
import MagicString from 'magic-string'

const ENTRIES: Record<string, string> = {
  react: 'https://esm.sh/react@19.3.1?target=es2022',
  'react/jsx-runtime': 'https://esm.sh/react@19.3.1/jsx-runtime?target=es2022',
  'react-dom/client': 'https://esm.sh/react-dom@19.3.1/client?target=es2022',
  'json-rpc-2.0': 'https://esm.sh/json-rpc-2.0@1.8.1?target=es2022',
  'object-inspect': 'https://esm.sh/object-inspect@1.13.4?target=es2022',
}

const OUT = path.join(import.meta.dir, '../src/lib/blocks/vendor')
const ESM = 'https://esm.sh'

const sri = (text: string) =>
  `sha384-${createHash('sha384').update(text).digest('base64')}`

async function get(url: string): Promise<string> {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  return response.text()
}

/** esm.sh answers a package URL with a stub that re-exports the real build. */
async function resolveBuild(url: string): Promise<string> {
  if (new URL(url).pathname.endsWith('.mjs')) return url
  const stub = await get(url)
  const target = /export \* from "([^"]+\.mjs)"/.exec(stub)?.[1]
  if (!target) throw new Error(`${url} is not an esm.sh stub`)
  return new URL(target, url).href
}

const servedPath = (url: string) => `/vendor${new URL(url).pathname}`

const served = new Map<
  string,
  { url: string; text: string; upstream: string }
>()

async function vendor(url: string): Promise<string> {
  const build = await resolveBuild(url)
  const at = servedPath(build)
  if (served.has(at)) return at
  served.set(at, { url: build, text: '', upstream: '' })
  const text = await get(build)
  const program = parse(text, { ecmaVersion: 'latest', sourceType: 'module' })
  const sources: Array<AcornNode & { value: string }> = []
  const collect = (node: { source?: AcornNode | null }) => {
    const source = node.source as (AcornNode & { value?: unknown }) | null
    if (source?.type === 'Literal' && typeof source.value === 'string')
      sources.push(source as AcornNode & { value: string })
  }
  simple(program, {
    ImportDeclaration: collect,
    ExportAllDeclaration: collect,
    ExportNamedDeclaration: collect,
    ImportExpression: collect,
  })
  const out = new MagicString(text)
  for (const source of sources) {
    const target = new URL(
      source.value,
      source.value.startsWith('/') ? ESM : build,
    )
    if (target.origin !== ESM)
      throw new Error(`${build} imports ${source.value} from outside esm.sh`)
    out.overwrite(
      source.start,
      source.end,
      JSON.stringify(await vendor(target.href)),
    )
  }
  served.set(at, { url: build, text: out.toString(), upstream: sri(text) })
  return at
}

const imports: Record<string, string> = {}
for (const [specifier, url] of Object.entries(ENTRIES))
  imports[specifier] = await vendor(url)

await rm(path.join(OUT, 'files'), { recursive: true, force: true })
const integrity: Record<string, string> = {}
const sources: Record<string, { url: string; integrity: string }> = {}
const raw: Array<[string, string]> = []
for (const [at, { url, text, upstream }] of [...served].sort()) {
  const file = path.join(OUT, 'files', at.slice('/vendor/'.length))
  await mkdir(path.dirname(file), { recursive: true })
  await writeFile(file, text)
  integrity[at] = sri(text)
  sources[at] = { url, integrity: upstream }
  raw.push([at, `./files/${at.slice('/vendor/'.length)}?raw`])
}

const importMap = { imports, integrity }
const importMapHash = createHash('sha256')
  .update(JSON.stringify(importMap))
  .digest('hex')
const json = (value: unknown) => JSON.stringify(value, null, 2)

await writeFile(
  path.join(OUT, 'manifest.ts'),
  `// SOURCING: generated by scripts/vendor-block-modules.ts from esm.sh builds;
// do not edit. The import map blocks run with, and where each file came from.

/** The import map every block document carries. */
export const importMap = ${json(importMap)}

/** SHA-256 of the import map; part of every compile cache key. */
export const importMapHash = '${importMapHash}'

/** The esm.sh build each served file was vendored from, and its integrity there. */
export const vendorSources: Record<string, { url: string; integrity: string }> = ${json(sources)}
`,
)

await writeFile(
  path.join(OUT, 'modules.ts'),
  `// SOURCING: generated by scripts/vendor-block-modules.ts; do not edit. The
// vendored modules' text, for the block listener and the standalone export.
${raw.map(([, file], i) => `import m${i} from '${file}'`).join('\n')}

/** Each vendored module's text by the path the listener serves it at. */
export const vendorModules: Record<string, string> = {
${raw.map(([at], i) => `  '${at}': m${i},`).join('\n')}
}
`,
)

console.log(
  `Vendored ${served.size} modules for ${Object.keys(imports).length} entries`,
)
